create or replace function public.sime_touch_updated_at()
returns trigger language plpgsql security invoker set search_path = public as $$
begin new.updated_at = now(); return new; end;
$$;

do $$
declare table_name text;
begin
  foreach table_name in array array['students','resources','assignment_submissions','ai_settings','ai_conversations','gamification_settings','intervention_notes','platform_settings','developer_api_settings'] loop
    execute format('create trigger %I_touch before update on public.%I for each row execute function public.sime_touch_updated_at()',table_name,table_name);
  end loop;
end $$;

create or replace function public.sime_change_notification()
returns trigger language plpgsql security invoker set search_path = public as $$
declare row_data jsonb := case when tg_op='DELETE' then to_jsonb(old) else to_jsonb(new) end;
declare tenant text := coalesce(row_data->>'tenant_id','platform');
declare label text := replace(tg_table_name,'_',' ');
begin
  if tg_table_name <> 'notifications' then
    insert into public.notifications(tenant_id,audience_role,category,title,message,link)
    values(tenant,'all','system',initcap(label)||' '||lower(tg_op),initcap(label)||' changed and is available now.','');
  end if;
  return case when tg_op='DELETE' then old else new end;
end;
$$;

do $$
declare table_name text;
begin
  foreach table_name in array array['students','resources','assignment_submissions','gamification_points','intervention_notes','security_settings','ai_settings','gamification_settings','developer_api_settings'] loop
    execute format('create trigger %I_notify after insert or update or delete on public.%I for each row execute function public.sime_change_notification()',table_name,table_name);
  end loop;
end $$;

