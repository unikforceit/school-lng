declare item record;
begin
  for item in select tablename from pg_tables where schemaname='public' loop
    execute format('alter table public.%I enable row level security',item.tablename);
    execute format('create policy server_only on public.%I for all to anon, authenticated using (false) with check (false)',item.tablename);
  end loop;
end $$;

